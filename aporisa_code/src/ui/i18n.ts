export const DICTIONARIES: Record<Language, Record<MessageKey, string>> = { en, "zh-CN": zhCN };

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function translator(language: Language): Translate {
  const dictionary = DICTIONARIES[language];
  return (key, values = {}) => dictionary[key].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

/** "7m 59s", "12s", "1h 3m" (zh-CN: "7 分 59 秒"). */
export function formatDuration(ms: number, language: Language): string {
  const total = Math.max(0, Math.round(ms / 1000));
  const hours = Math.floor(total / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  const seconds = total % 60;
  if (language === "zh-CN") {
    if (hours > 0) return `${hours} 小时 ${minutes} 分`;
    if (minutes > 0) return `${minutes} 分 ${seconds} 秒`;
    return `${seconds} 秒`;
  }
  if (hours > 0) return `${hours}h ${minutes}m`;
  if (minutes > 0) return `${minutes}m ${seconds}s`;
  return `${seconds}s`;
}

/** 12.3K, 262K. */
export function formatTokens(tokens: number, language: Language): string {
  return new Intl.NumberFormat(language, { notation: "compact", maximumFractionDigits: 1 }).format(tokens);
}

/** Compact age for list rows: "now", "5m", "3h", "2d", "3w", "4mo", "1y" (zh-CN: "刚刚", "5 分钟"…). */
export function formatAge(timestamp: number, now: number, language: Language): string {
  const minutes = Math.max(0, Math.floor((now - timestamp) / 60_000));
  const steps: [number, string, string][] = [
    [60, "m", " 分钟"],
    [24, "h", " 小时"],
    [7, "d", " 天"],
    [52 / 12, "w", " 周"],
    [12, "mo", " 个月"],
    [Number.POSITIVE_INFINITY, "y", " 年"],
  ];
  if (minutes < 1) return language === "zh-CN" ? "刚刚" : "now";
  let value = minutes;
  for (const [size, en, zh] of steps) {
    if (value < size) return `${Math.floor(value)}${language === "zh-CN" ? zh : en}`;
    value /= size;
  }
  return "";
}
